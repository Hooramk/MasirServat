package ir.masirservat.app;

public class StoryRepository {
    public static String chapterName(int month) {
        if (month <= 6) return "فصل ۱ · روی پای خودت";
        if (month <= 12) return "فصل ۲ · نفس‌کشیدن وسط تورم";
        if (month <= 18) return "فصل ۳ · ساختن پشتوانه";
        if (month <= 24) return "فصل ۴ · رشد هوشمند";
        return "فصل ۵ · نزدیک آزادی مالی";
    }

    public static String chapterMission(int month) {
        if (month <= 6) return "ماموریت: جریان نقدی مثبت نگه دار و اولین پشتوانه امن را بساز.";
        if (month <= 12) return "ماموریت: زیر فشار تورم، بدهی مصرفی را کنترل و درآمدت را تقویت کن.";
        if (month <= 18) return "ماموریت: دارایی‌هایت را متنوع کن، بدون اینکه نقدینگی را قربانی کنی.";
        if (month <= 24) return "ماموریت: درآمد دوم یا کسب‌وکار را رشد بده و جلوی تورم سبک زندگی را بگیر.";
        return "ماموریت: درآمد غیرفعال را به هزینه‌های ضروری نزدیک کن.";
    }

    public static String story(String eventId, String career) {
        String job = career == null ? "کارت" : career;
        switch (eventId) {
            case "EV01": return "تهران، عصر پنج‌شنبه. بعد از یک هفته شلوغِ "+job+"، جلوی ویترین موبایل می‌ایستی. گوشی جدید براق است؛ گوشی خودت اما هنوز کاملاً کار می‌کند.";
            case "EV02": return "صبح جمعه برای خرید هفتگی می‌روی. همان سبد همیشگی این بار خیلی گران‌تر تمام می‌شود. فروشنده می‌گوید: «قیمت‌ها دوباره بالا رفته.»";
            case "EV03": return "شب، برق می‌رود و تو مانده‌ای با فکر یک سؤال ساده: اگر فردا درآمدت قطع شود، چند ماه دوام می‌آوری؟";
            case "EV04": return "یک تماس ناگهانی برنامه ماه را به‌هم می‌زند: هزینه درمانی که اصلاً انتظارش را نداشتی. الان مهم‌ترین چیز، سرعت تصمیم‌گیری است.";
            case "EV05": return "سه ماه است بیشتر از شرح وظیفه‌ات کار می‌کنی. مدیرت از عملکردت راضی است. زمان خوبی برای یک گفت‌وگوی سخت اما مهم رسیده.";
            case "EV06": return "صبح شبکه‌های خبری پر از حرف نرخ ارز است. قیمت کالاهای وارداتی ظرف چند ساعت عوض می‌شود و ترسِ «الان نخرم گران‌تر می‌شود» سراغت می‌آید.";
            case "EV07": return "یک پیام بانکی: «وام فوری با اقساط آسان». عدد پول وسوسه‌کننده است؛ اما هر وام، بخشی از درآمد آینده‌ات را از قبل خرج می‌کند.";
            case "EV08": return "صاحبخانه تماس گرفته. قرارداد رو به پایان است. روی میز دو انتخاب داری: ماندن با اجاره بیشتر یا جابه‌جایی با دردسر و هزینه.";
            case "EV09": return "یکی از دوستانت یک پروژه جانبی پیشنهاد می‌دهد. درآمدش خوب است، ولی یعنی چند شب در هفته زمان آزاد کمتری خواهی داشت.";
            case "EV10": return "چند نفر اطرافت مدام درباره طلا حرف می‌زنند. تو مقداری پول نقد داری و باید بین حفظ نقدینگی و پوشش تورم تعادل بسازی.";
            case "EV11": return "صبح ماشین روشن نمی‌شود. مکانیک دو نسخه دارد: تعمیر کاملِ گران، یا راه‌حل موقتیِ ارزان.";
            case "EV12": return "یکی از وسایل خانه از کار افتاده. فروشنده با لبخند می‌گوید: «قسطی بردار، ماهی چیزی نمی‌شود.» اما جمع اقساط داستان دیگری دارد.";
            case "EV13": return "صورت‌حساب ماهانه را نگاه می‌کنی: چند اشتراک کوچک، چند خرید خودکار، چند پرداختی که حتی یادت نبود هنوز فعال‌اند.";
            case "EV14": return "یک مراسم خانوادگی نزدیک است. دوست داری آبرومندانه حاضر شوی، اما بودجه این ماه کشش ولخرجی ندارد.";
            case "EV15": return "تعطیلات رسیده. همه از سفر حرف می‌زنند. تو هم خسته‌ای، اما می‌دانی لذت امروز نباید تبدیل به فشار شش ماه آینده شود.";
            case "EV16": return "یکی از همکارانت از هزینه سنگین درمانش می‌گوید. ناگهان موضوع بیمه از یک خرج اضافی، تبدیل به یک سؤال جدی می‌شود.";
            case "EV17": return "یک آشنا با اطمینان می‌گوید: «این سرمایه‌گذاری ضرر ندارد؛ ماهی سود ثابت می‌دهد.» جمله بیش از حد خوب به نظر می‌رسد.";
            case "EV18": return "دوره‌ای پیدا کرده‌ای که می‌تواند مهارتت را بالا ببرد. هزینه‌اش کم نیست، ولی شاید درآمد آینده‌ات را تغییر دهد.";
            case "EV19": return "یک صبح معمولی با یک خبر غیرمعمول شروع می‌شود: فعلاً کاری در کار نیست. حالا همه تصمیم‌های ماه‌های قبل معنی تازه‌ای پیدا می‌کنند.";
            case "EV20": return "یک پیشنهاد شغلی جدید داری؛ حقوق بیشتر، مسیر طولانی‌تر و هزینه رفت‌وآمد بالاتر. عدد حقوق به‌تنهایی جواب را نمی‌دهد.";
            case "EV21": return "بازار قرمز شده. ارزش سرمایه‌گذاری‌ات پایین آمده و دستت روی دکمه فروش است. ترس، بلندتر از برنامه‌ات حرف می‌زند.";
            case "EV22": return "درآمدت بهتر شده و اطرافیانت می‌گویند وقتش است ماشینت را عوض کنی. سؤال این است: رشد درآمد یا رشد سبک زندگی؟";
            case "EV23": return "یک مبلغ اضافه دستت آمده. هم بدهی داری، هم فرصت سرمایه‌گذاری. هر دو انتخاب منطقی به نظر می‌رسند، اما نرخ‌ها تعیین‌کننده‌اند.";
            case "EV24": return "ایده‌ای داری که شاید تبدیل به درآمد شود. هیجان می‌گوید بزرگ شروع کن؛ تجربه می‌گوید اول کوچک امتحان کن.";
            case "EV25": return "فروش بد نیست، ولی ته ماه پولی نمانده. تازه متوجه می‌شوی هزینه‌هایی وجود دارند که در حساب اولیه ندیده بودی.";
            case "EV26": return "یک پاداش غیرمنتظره گرفته‌ای. وسوسه خرید زیاد است، اما این پول می‌تواند سرعت ساخت پشتوانه‌ات را هم بالا ببرد.";
            case "EV27": return "درآمدت بالاتر رفته و ناخودآگاه خرج‌ها هم بالا آمده‌اند. زندگی بهتر شده؛ اما آیا ثروتت هم بیشتر شده؟";
            case "EV28": return "برای خانه بعدی دو قرارداد جلویت است: پول بیشتری رهن بدهی و اجاره کمتر، یا نقدینگی‌ات را نگه داری و اجاره بیشتری بدهی.";
            case "EV29": return "یکی از نزدیکانت کمک مالی می‌خواهد. کمک کردن ارزشمند است، اما اگر خودت را وارد بحران کند، دو نفر گرفتار می‌شوند.";
            case "EV30": return "یک سال گذشته. دفترچه تصمیم‌ها را ورق می‌زنی: بعضی انتخاب‌ها عالی بودند، بعضی نه. حالا وقت اصلاح مسیر است.";
            default: return "یک ماه تازه شروع شده و یک تصمیم مالی تازه روبه‌روی توست.";
        }
    }

    public static String mentor(int month) {
        String[] tips = {
            "رها: «پول فقط عدد نیست؛ آزادی انتخابِ آینده است.»",
            "رها: «قبل از خرید، از خودت بپرس این تصمیم جریان نقدی ماه بعد را چه می‌کند؟»",
            "رها: «تورم، پول را بی‌صدا کوچک می‌کند؛ دارایی واقعی را ببین، نه فقط عدد حساب را.»",
            "رها: «صندوق اضطراری برای سود کردن نیست؛ برای مجبور نشدن به تصمیم بد است.»",
            "رها: «هر افزایش درآمدی که کامل خرج شود، تو را ثروتمندتر نمی‌کند.»"
        };
        return tips[(month-1)%tips.length];
    }
}
